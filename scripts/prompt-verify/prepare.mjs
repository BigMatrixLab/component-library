// Prepare an isolated route for one blind-test run.
//   node scripts/prompt-verify/prepare.mjs <slug>
// Expects the AI output in apps/verify/output/<slug>/ (ui/** + app/example.tsx).
// Creates apps/verify/app/v/<slug>/{page.tsx,styles.css} that render ONLY that
// output with ONLY its own CSS (Tailwind + its kit.css), and rewrites the
// example's "@/ui" imports to the run's own ui folder.
import { mkdir, readFile, writeFile, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const slug = process.argv[2];
if (!slug || !/^[a-z0-9-]+$/.test(slug)) throw new Error('Usage: prepare.mjs <slug> (a-z, 0-9, -)');
const root = resolve('apps/verify');
const out = join(root, 'output', slug);
const example = join(out, 'app', 'example.tsx');
await stat(example).catch(() => {
  throw new Error(`Missing ${example}`);
});

let src = await readFile(example, 'utf8');
src = src.replace(/from\s+['"]@\/ui['"]/g, "from '../ui'").replace(/from\s+['"]@\/ui\/([^'"]+)['"]/g, "from '../ui/$1'");
await writeFile(example, src);

const route = join(root, 'app', 'v', slug);
await mkdir(route, { recursive: true });
await writeFile(
  join(route, 'styles.css'),
  `/* Generated: Tailwind + this run's own kit only. */\n@import "tailwindcss";\n@import "../../../output/${slug}/ui/styles/kit.css";\n@source "../../../output/${slug}/**/*.{ts,tsx}";\n`,
);
await writeFile(
  join(route, 'page.tsx'),
  `/* Generated by scripts/prompt-verify/prepare.mjs */\nimport './styles.css';\nimport Example from '../../../output/${slug}/app/example';\n\nexport default function Run() {\n  return (\n    <main data-verify-preview className="flex min-h-44 flex-wrap items-center justify-center gap-3 p-10">\n      <Example />\n    </main>\n  );\n}\n`,
);
console.log(`ready: http://localhost:4322/v/${slug}`);
