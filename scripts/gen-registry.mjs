// `npm run gen:registry` — emit a shadcn-compatible registry into apps/docs/public/r/.
//
//   apps/docs/public/r/<component>.json   one registry item per component (source included)
//   apps/docs/public/r/theme.json         tokens, base and motion CSS + a theme.css entry
//   apps/docs/public/r/all.json           every component in one go
//   apps/docs/public/r/index.json         the registry index (registry.json schema, no content)
//
// Install with:  npx shadcn@latest add https://<site>/r/button.json
//
// Environment:
//   UI_SITE_URL          public origin of the docs site (default: placeholder)
//   UI_REGISTRY_TARGET   folder the source is copied into, relative to the app
//                        (default "ui"; shadcn puts it under src/ when the app uses src/)
//
// Files keep the packages/ui/src layout under the target folder, so the library's
// relative imports work unchanged and no import rewriting is needed.
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  PKG_NAME,
  SITE_URL,
  UI_SRC,
  componentGraph,
  componentNames,
  docsNav,
  read,
  readRepo,
  repoRoot,
  specSummary,
  titleCase,
} from './lib/source.mjs';

const OUT = join(repoRoot, 'apps', 'docs', 'public', 'r');
const TARGET = (process.env.UI_REGISTRY_TARGET || 'ui').replace(/^\.?\/+|\/+$/g, '');
const ITEM_SCHEMA = 'https://ui.shadcn.com/schema/registry-item.json';
const INDEX_SCHEMA = 'https://ui.shadcn.com/schema/registry.json';
const itemUrl = (name) => `${SITE_URL}/r/${name}.json`;

/** shadcn file type for a path under packages/ui/src. */
function fileType(srcPath) {
  if (srcPath.endsWith('.css')) return 'registry:file';
  if (srcPath.startsWith('hooks/')) return 'registry:hook';
  if (srcPath.startsWith('components/')) return 'registry:ui';
  return 'registry:lib';
}

const fileEntry = (srcPath, content = read(join(UI_SRC, srcPath))) => ({
  path: `${PKG_NAME}/${srcPath}`,
  type: fileType(srcPath),
  target: `${TARGET}/${srcPath}`,
  content,
});

/* ---------------------------------------------------------------------------
   Theme item: the non-component imports of kit.css, in kit.css order, plus a
   theme.css entry that imports them and points Tailwind at the source. */

function themeItem() {
  const kit = readRepo('packages/ui/src/styles/kit.css');
  const imports = [...kit.matchAll(/@import\s+["']\.\/([^"']+)["']/g)]
    .map((m) => m[1])
    .filter((p) => !p.startsWith('components/'));
  const entry = [
    `/* ${PKG_NAME} theme entry, generated by scripts/gen-registry.mjs.`,
    '   In your global CSS, after @import "tailwindcss":',
    `     @import "<path-to>/${TARGET}/styles/theme.css";`,
    '   then one line per component you add, for example:',
    `     @import "<path-to>/${TARGET}/styles/components/button.css"; */`,
    '',
    ...imports.map((p) => `@import "./${p}";`),
    '',
    '/* Let Tailwind see the utility classes used inside the components */',
    '@source "..";',
    '',
  ].join('\n');

  return {
    $schema: ITEM_SCHEMA,
    name: 'theme',
    type: 'registry:lib',
    title: `${titleCase(PKG_NAME)} theme`,
    description: 'Design tokens (palette, semantic roles, accents, theme packs), base styles and motion presets.',
    dependencies: [],
    registryDependencies: [],
    files: [...imports.map((p) => fileEntry(`styles/${p}`)), fileEntry('styles/theme.css', entry)],
    docs: `Import "${TARGET}/styles/theme.css" in your global CSS after @import "tailwindcss".`,
  };
}

/* ---------------------------------------------------------------------------
   Component items */

function componentItem(name, nav) {
  const g = componentGraph(name);
  if (!g) return null;
  const specPath = `prompts/components/${name}.md`;
  const spec = existsSync(join(repoRoot, specPath)) ? specSummary(readRepo(specPath)) : {};
  const doc = nav.get(name);

  const files = [...g.files, ...g.helpers, ...(g.css ? [g.css] : [])].map((p) => fileEntry(p));
  const cssLine = g.css ? `@import "<path-to>/${TARGET}/${g.css}";` : null;
  const example = g.exports.length ? `import { ${g.exports.slice(0, 3).join(', ')} } from '@/${TARGET}/components/${name}';` : '';

  return {
    $schema: ITEM_SCHEMA,
    name,
    type: 'registry:ui',
    title: doc?.title ?? spec.title ?? titleCase(name),
    description: doc?.description || spec.description || '',
    dependencies: g.dependencies,
    registryDependencies: [itemUrl('theme'), ...g.components.map(itemUrl)],
    files,
    docs: [cssLine && `Add to your global CSS: ${cssLine}`, example && `Use it: ${example}`].filter(Boolean).join('\n'),
    meta: { exports: g.exports, components: g.components },
  };
}

/* ---------------------------------------------------------------------------
   Write */

const nav = docsNav();
const items = [themeItem()];
for (const name of componentNames()) {
  const item = componentItem(name, nav);
  if (item) items.push(item);
}
const componentItems = items.filter((i) => i.name !== 'theme');
items.push({
  $schema: ITEM_SCHEMA,
  name: 'all',
  type: 'registry:ui',
  title: `All ${PKG_NAME} components`,
  description: 'Every component, its helpers and its CSS.',
  dependencies: [],
  registryDependencies: [itemUrl('theme'), ...componentItems.map((i) => itemUrl(i.name))],
  files: [],
});

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const item of items) writeFileSync(join(OUT, `${item.name}.json`), `${JSON.stringify(item, null, 2)}\n`);

const index = {
  $schema: INDEX_SCHEMA,
  name: PKG_NAME,
  homepage: SITE_URL,
  items: items.map(({ $schema, files, docs, ...rest }) => ({
    ...rest,
    files: files.map(({ content, ...f }) => f),
  })),
};
writeFileSync(join(OUT, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);

const totalFiles = items.reduce((n, i) => n + i.files.length, 0);
console.log(`gen-registry: ${items.length} items (${totalFiles} files) → apps/docs/public/r  [site ${SITE_URL}, target ${TARGET}/]`);
