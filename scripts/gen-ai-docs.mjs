// `npm run gen:ai` — copy-paste install docs for AI coding tools, committed in ai/.
//
//   ai/README.md                what this is, how to use it, every doc's URL
//   ai/setup.md                 one-time setup: alias, tokens/base/motion CSS, kit.css entry, ThemeScript
//   ai/components/<name>.md     one component: agent instructions, spec, every file verbatim, usage
//   ai/blocks/<name>.md         one block: agent instructions, spec, every variant's source
//
// A teammate pastes one GitHub URL (blob or raw) into their AI tool; the doc
// tells the agent exactly which files to create where. No npm package, no CLI.
//
// Sources: packages/ui/src (import graph from scripts/lib/source.mjs), prompts/,
// apps/docs/examples/, apps/docs/lib/registry.ts (titles), apps/docs/app/docs/**/page.tsx
// (example order). Output is deterministic: sorted, no timestamps, LF endings.
// CI fails when ai/ is stale (.github/workflows/ci.yml, unit job).
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { componentGraph, componentNames, docsNav, readRepo, repoRoot, specSummary, titleCase } from './lib/source.mjs';
import {
  GH_BRANCH,
  GH_REPO,
  TARGET,
  demote,
  examplesFor,
  exportMap,
  fence,
  fileBlock,
  ghUrl,
  helperClosure,
  lines,
  moduleFile,
  rawUrl,
  readRepoLf,
  readSrc,
  rewriteExample,
  setupCss,
  srcRawUrl,
  target,
} from './lib/ai-docs.mjs';

const OUT = join(repoRoot, 'ai');
const GENERATED = '<!-- Generated by scripts/gen-ai-docs.mjs (npm run gen:ai). Do not edit by hand. -->';
const peers = JSON.parse(readRepo('packages/ui/package.json')).peerDependencies ?? {};
const REACT = peers.react ?? '>=18.2';

const docPath = {
  setup: 'ai/setup.md',
  readme: 'ai/README.md',
  component: (n) => `ai/components/${n}.md`,
  block: (n) => `ai/blocks/${n}.md`,
};

/* ---------------------------------------------------------------------------
   Data */

const nav = docsNav();
const graphs = new Map();
for (const name of componentNames()) {
  const g = componentGraph(name);
  if (g) graphs.set(name, g);
}
const names = [...graphs.keys()].sort();
const map = exportMap([...graphs.values()]);
const warnings = [];

/** Every file a component brings, without its component dependencies. */
const ownFiles = (name) => {
  const g = graphs.get(name);
  return [...g.files, ...g.helpers, ...(g.css ? [g.css] : [])];
};

/** `roots` and every component they use, transitively, dependencies first. */
function topo(roots) {
  const order = [];
  const seen = new Set();
  const visit = (n) => {
    if (seen.has(n) || !graphs.has(n)) return;
    seen.add(n);
    graphs.get(n).components.forEach(visit);
    order.push(n);
  };
  [...roots].sort().forEach(visit);
  return order;
}

function meta(kind, name) {
  const specPath = `prompts/${kind}/${name}.md`;
  const spec = existsSync(join(repoRoot, specPath)) ? readRepoLf(specPath).trimEnd() : null;
  const sum = spec ? specSummary(spec) : {};
  const doc = nav.get(name);
  const fallback = kind === 'blocks' ? `${titleCase(name)} block` : titleCase(name);
  return {
    spec: spec ?? `## ${kind === 'blocks' ? 'Block' : 'Component'}: ${titleCase(name)}\n\n(Spec pending.)`,
    title: doc?.title ?? sum.title ?? fallback,
    description: doc?.description || sum.description || '',
  };
}

/** Rewrite one example; record anything that could not be mapped. */
function example(path) {
  const r = rewriteExample(readRepoLf(path), map);
  if (r.unknown.length) warnings.push(`${path}: no module for ${r.unknown.join(', ')}`);
  return r;
}

/* ---------------------------------------------------------------------------
   Shared Markdown pieces */

const link = (path) => `[${path.replace(/^ai\//, '')}](${rawUrl(path)})`;
const cssLine = (n) => `@import "./components/${n}.css";`;

function downloadScript(files) {
  const sorted = [...new Set(files)].sort();
  return fence(
    'x.sh',
    [
      '# Run from the folder the @/ alias points to (src/ or the project root).',
      '# Windows PowerShell: type curl.exe instead of curl.',
      ...sorted.map((f) => `curl -fsSL --create-dirs -o ${target(f)} ${srcRawUrl(f)}`),
    ].join('\n'),
  );
}

/** Number a list of steps; a step may carry an indented code block after its first line. */
const numbered = (steps) => steps.filter(Boolean).map((s, i) => `${i + 1}. ${s}`);
const indent = (block) => block.replace(/^(?=.)/gm, '   ');

const cssStep = (cssLines) =>
  cssLines.length
    ? `**Register the CSS.** In \`${TARGET}/styles/kit.css\`, add ${cssLines.length === 1 ? 'this line' : 'these lines'} directly above the \`@source\` line, skipping any already there:\n\n${indent(fence('x.css', cssLines.join('\n')))}\n`
    : null;

const setupStep = () =>
  `**Setup first.** Look for \`${TARGET}/styles/kit.css\` in the folder the \`@/\` import alias points to (\`src/\` in most Next.js apps, otherwise the project root). If it is missing, apply the one-time setup first: ${rawUrl(docPath.setup)}`;

const RULES = [
  '**Rules.** Copy every file verbatim: do not restyle, rename classes, reformat, "improve", convert to another styling',
  'approach (CSS modules, styled-components, inline styles) or add npm packages. React and Tailwind CSS v4 only.',
  'Keep `\'use client\'` lines where they are. If a file already exists with identical contents, leave it.',
  'Fetch this doc and the source files as raw text (for example with `curl`), not through a summarising web reader:',
  'the code must arrive character for character.',
].join(' ');

/* ---------------------------------------------------------------------------
   ai/components/<name>.md */

function componentDoc(name) {
  const g = graphs.get(name);
  const m = meta('components', name);
  const deps = topo([name]).filter((c) => c !== name);
  const first = examplesFor(name, `apps/docs/app/docs/components/${name}/page.tsx`)[0] ?? null;
  const ex = first ? example(first.path) : null;

  // Files the usage example needs beyond this component (e.g. icons), and components it also renders
  const exHelpers = ex ? helperClosure(ex.modules.map(moduleFile).filter(Boolean)) : { files: [], components: [] };
  const own = ownFiles(name);
  const files = [...own, ...exHelpers.files.filter((f) => !own.includes(f))];
  const all = topo([name, ...(ex?.components ?? []), ...exHelpers.components]);
  const exAll = all.filter((c) => c !== name && !deps.includes(c));

  const cssLines = all.filter((n) => graphs.get(n).css).map(cssLine);
  const npm = [...new Set(all.flatMap((n) => graphs.get(n).dependencies))].sort();
  const script = downloadScript([...files, ...[...deps, ...exAll].flatMap(ownFiles)]);
  // Components (PascalCase) first, then hooks and helpers
  const shown = [...g.exports].sort((a, b) => Number(!/^[A-Z]/.test(a)) - Number(!/^[A-Z]/.test(b)));
  const importLine = g.exports.length
    ? `import { ${shown.slice(0, 4).join(', ')}${shown.length > 4 ? ', …' : ''} } from '@/${TARGET}/components/${name}';`
    : null;
  const docList = (cs) => cs.map((d) => `   - \`${d}\`: ${rawUrl(docPath.component(d))}`).join('\n');

  const steps = numbered([
    setupStep(),
    npm.length && `**npm packages.** \`npm install ${npm.join(' ')}\``,
    deps.length
      ? `**Components it uses.** ${m.title} imports ${deps.length === 1 ? 'another component' : `${deps.length} other components`}. Install them first, in this order, skipping any already in \`${TARGET}/components/\`. Each doc lists its files; the download script below covers them too.\n${docList(deps)}`
      : `**Components it uses.** None: ${m.title} only needs the files below.`,
    `**Create the files.** Create every file under [Files](#files) at its exact path, with exactly the contents shown. If you can run shell commands, the download script below does this${deps.length ? ' and the step before' : ''} in one go.`,
    cssStep(cssLines),
    exAll.length &&
      `**Usage example only.** The example also renders ${exAll.length === 1 ? 'this component' : 'these components'}; install ${exAll.length === 1 ? 'it' : 'them'} if you use the example as-is (the download script and the CSS lines above include ${exAll.length === 1 ? 'it' : 'them'}):\n${docList(exAll)}`,
    `**Use it.** ${importLine ? `\`${importLine}\` See ` : 'See '}[Usage](#usage). Tell the user which files you created.`,
  ]);

  return lines(
    `# ${m.title}`,
    '',
    m.description && `> ${m.description}`,
    '',
    GENERATED,
    '',
    `Install doc for the **${m.title}** component of ui-kit: React ${REACT} + TypeScript + Tailwind CSS v4, no npm package. Source: ${ghUrl(`packages/ui/src/components/${name}`)}`,
    '',
    '## Instructions for the AI agent',
    '',
    `Add ${m.title} to this project exactly as specified here.`,
    '',
    steps,
    '',
    RULES,
    '',
    '### Download script',
    '',
    `Creates every file this component needs, including the components it uses${exAll.length ? ' and those in the usage example' : ''}. Steps 1 and "Register the CSS" still apply.`,
    '',
    script,
    '',
    '## Specification',
    '',
    demote(m.spec),
    '',
    '## Files',
    '',
    `Paths are relative to the folder the \`@/\` alias points to. The folder keeps the library's own layout, so the relative imports inside the files work unchanged.${deps.length ? ' Files of the components it uses are in their own docs (see Instructions).' : ''}`,
    '',
    files.map((f) => `${fileBlock(target(f), readSrc(f))}\n`),
    '## Usage',
    '',
    ex
      ? [`${first.title ? `**${first.title}** — f` : 'F'}rom the docs (\`${first.path}\`), imports rewritten to \`@/${TARGET}/...\`:`, '', fence('x.tsx', ex.code)]
      : [importLine ? fence('x.tsx', importLine) : 'See the specification above.'],
  );
}

/* ---------------------------------------------------------------------------
   ai/blocks/<name>.md */

function blockDoc(name) {
  const m = meta('blocks', name);
  m.title = /block$/i.test(m.title) ? m.title : `${m.title} block`;
  const variants = examplesFor(`blocks/${name}`, `apps/docs/app/docs/blocks/${name}/page.tsx`).map((v) => ({ ...v, ex: example(v.path) }));
  const used = [...new Set(variants.flatMap((v) => v.ex.components))].sort();
  const helpers = helperClosure(variants.flatMap((v) => v.ex.modules.map(moduleFile).filter(Boolean)));
  const install = topo([...used, ...helpers.components]);
  const cssLines = install.filter((n) => graphs.get(n).css).map(cssLine);
  const script = downloadScript([...helpers.files, ...install.flatMap(ownFiles)]);
  const blockDir = `components/blocks/${name}`;
  const steps = numbered([
    setupStep(),
    `**Install these components first**, in this order, skipping any already in \`${TARGET}/components/\`. Follow each one's doc, or run the download script below, which covers all of them:\n${install.map((c) => `   - \`${c}\`: ${rawUrl(docPath.component(c))}`).join('\n')}`,
    helpers.files.length && `**Shared files.** Create the files under [Shared files](#shared-files) at their exact paths (the download script covers them).`,
    cssStep(cssLines),
    `**Create the block.** Save the variant verbatim as its own file, for example \`${blockDir}/<variant>.tsx\` inside the \`@/\` folder, then render it from a page. Change the copy (names, prices, links) only if the user asks.`,
  ]);

  return lines(
    `# ${m.title}`,
    '',
    m.description && `> ${m.description}`,
    '',
    GENERATED,
    '',
    `Install doc for the **${m.title}** of ui-kit: ${variants.length} variant${variants.length === 1 ? '' : 's'} built only from ui-kit components. React ${REACT} + TypeScript + Tailwind CSS v4.`,
    '',
    '## Instructions for the AI agent',
    '',
    `Add the ${m.title} to this project exactly as specified here. If the user did not say which variant, ask, or install the first one.`,
    '',
    steps,
    '',
    RULES,
    '',
    '### Download script',
    '',
    script,
    '',
    '## Specification',
    '',
    demote(m.spec),
    '',
    '## Variants',
    '',
    'Imports are rewritten from the package to the local files (`@/ui/...`).',
    '',
    variants.map((v) => [`### ${v.title ?? titleCase(v.base)}`, '', `File: \`${blockDir}/${v.base}.tsx\` (docs source: \`${v.path}\`)`, '', fence('x.tsx', v.ex.code), '']),
    helpers.files.length ? ['## Shared files', '', helpers.files.map((f) => `${fileBlock(target(f), readSrc(f))}\n`)] : null,
  );
}

/* ---------------------------------------------------------------------------
   ai/setup.md */

function setupDoc() {
  const css = setupCss();
  const theme = helperClosure(['theme/theme-script.tsx', 'theme/use-theme.ts']).files;
  const topLevel = [...readSrc('styles/kit.css').matchAll(/@import\s+["']\.\/([^"']+)["']/g)]
    .map((x) => x[1])
    .filter((p) => !p.startsWith('components/'));
  const kitCss = [
    '/* ui-kit entry, from ai/setup.md. Import it from your global CSS after @import "tailwindcss".',
    '   Each component install doc adds one @import line above @source. */',
    ...topLevel.map((p) => `@import "./${p}";`),
    '',
    '/* Components (one line per installed component, added by its install doc) */',
    '',
    '/* Let Tailwind see the utility classes used inside ui/ */',
    '@source "..";',
  ].join('\n');

  return lines(
    '# ui-kit setup (once per project)',
    '',
    GENERATED,
    '',
    'Run this once before installing any ui-kit component. Component docs check for `ui/styles/kit.css`; when it exists, setup is done.',
    '',
    '## Instructions for the AI agent',
    '',
    `1. **Check prerequisites.** React ${REACT} and react-dom, TypeScript, and **Tailwind CSS v4** (the global CSS starts with \`@import "tailwindcss";\`). Tailwind v3 is not supported: stop and tell the user. No other npm packages are needed.`,
    `2. **Pick the folder.** All files go in \`${TARGET}/\` inside the folder the \`@/\` import alias points to: \`src/${TARGET}/\` when the app has a \`src/\` folder, otherwise \`./${TARGET}/\`. Imports always read \`@/${TARGET}/...\`.`,
    '3. **Alias.** If `tsconfig.json` (or `jsconfig.json`) has no `@/*` path, add it (Next.js usually has it already). Vite also needs the same alias in `vite.config`:',
    '',
    indent(fence('x.json', '{\n  "compilerOptions": {\n    "baseUrl": ".",\n    "paths": { "@/*": ["./src/*"] }\n  }\n}')),
    '',
    '   Use `["./*"]` instead when there is no `src/` folder.',
    `4. **Create the files** under [Files](#files) verbatim (or run the download script), plus \`${TARGET}/styles/kit.css\` exactly as shown under [Entry CSS](#entry-css).`,
    '5. **Global CSS.** In the app\'s global stylesheet (Next.js: `app/globals.css` or `src/app/globals.css`), keep `@import "tailwindcss";` first and add the kit right after it. The path is relative to the stylesheet; for `app/globals.css` with `ui/` at the root, or `src/app/globals.css` with `src/ui/`, it is:',
    '',
    indent(fence('x.css', `@import "tailwindcss";\n@import "../${TARGET}/styles/kit.css";`)),
    '',
    '6. **Theme script** (applies the saved light/dark mode, accent and theme pack before the first paint). Next.js App Router, `app/layout.tsx`:',
    '',
    indent(fence(
      'x.tsx',
      [
        `import { ThemeScript } from '@/${TARGET}/theme/theme-script';`,
        "import './globals.css';",
        '',
        'export default function RootLayout({ children }: { children: React.ReactNode }) {',
        '  return (',
        '    <html lang="en" suppressHydrationWarning>',
        '      <head>',
        '        <ThemeScript />',
        '      </head>',
        '      <body>{children}</body>',
        '    </html>',
        '  );',
        '}',
      ].join('\n'),
    )),
    '',
    `   Keep the app's existing layout and only add the import, \`suppressHydrationWarning\` on \`<html>\` and \`<ThemeScript />\` in \`<head>\`. Vite / plain React: put the string \`themeBootScript\` from \`${TARGET}/theme/theme-script.tsx\` in a \`<script>\` in \`index.html\`'s \`<head>\`. Client components switch theme with \`useTheme()\` from \`@/${TARGET}/theme/use-theme\`.`,
    '7. Tell the user setup is done, then continue with the component doc that sent you here.',
    '',
    RULES,
    '',
    '## Folder layout after setup',
    '',
    fence(
      'x.txt',
      [
        `${TARGET}/`,
        '  styles/',
        '    kit.css              entry: tokens, base, motion, then one line per component',
        '    tokens/ base.css motion.css',
        '    components/<name>.css   added per component',
        '  theme/                 ThemeScript and useTheme',
        '  components/<name>/     added per component',
        '  lib/ hooks/ icons/     shared helpers, added with the components that use them',
      ].join('\n'),
    ),
    '',
    '### Download script',
    '',
    downloadScript([...css, ...theme]),
    '',
    '## Entry CSS',
    '',
    fileBlock(`${TARGET}/styles/kit.css`, kitCss),
    '',
    '## Files',
    '',
    [...css, ...theme].map((f) => `${fileBlock(target(f), readSrc(f))}\n`),
  );
}

/* ---------------------------------------------------------------------------
   ai/README.md */

function readme(blocks) {
  const row = (title, desc, path) => `| ${title} | ${desc.replace(/\|/g, '\\|')} | [GitHub](${ghUrl(path)}) | [raw](${rawUrl(path)}) |`;
  const table = ['| Name | What it is | Doc | Raw URL |', '|---|---|---|---|'];
  return lines(
    '# ui-kit for AI coding tools',
    '',
    GENERATED,
    '',
    'One Markdown file per component and block. Each file tells an AI coding agent (Claude Code, Cursor, Copilot, …) exactly which files to create in a React or Next.js app on Tailwind CSS v4, with every file\'s full contents. No npm package, no CLI.',
    '',
    '## How to use it',
    '',
    '1. Find the component below and copy its URL (the GitHub page or the raw link both work; raw is easiest for tools to read).',
    '2. Paste it to your AI tool:',
    '',
    fence('x.txt', `Add this component to my app: ${rawUrl(docPath.component('button'))}`),
    '',
    `3. The first time, the doc sends the agent to [setup.md](${ghUrl(docPath.setup)}) (tokens, base CSS, theme script). After that each component is one paste.`,
    '',
    'If this repo is private, the agent needs GitHub access to read the URLs (for example `gh` signed in); otherwise open the doc on GitHub and paste its contents instead.',
    '',
    '## What ends up in your app',
    '',
    fence(
      'x.txt',
      [
        `src/${TARGET}/            (or ./${TARGET}/ when there is no src/ folder; imported as @/${TARGET}/...)`,
        '  styles/kit.css      imported once from your global CSS, after @import "tailwindcss"',
        '  styles/tokens/ base.css motion.css components/<name>.css',
        '  theme/              ThemeScript + useTheme',
        '  components/<name>/  one folder per installed component',
        '  lib/ hooks/ icons/  shared helpers',
      ].join('\n'),
    ),
    '',
    `Import as \`import { Button } from '@/${TARGET}/components/button';\`. Files keep the library's own layout, so they can be updated by re-running a doc.`,
    '',
    '## Setup',
    '',
    `| Doc | Raw URL |\n|---|---|\n| [setup.md](${ghUrl(docPath.setup)}) | [raw](${rawUrl(docPath.setup)}) |`,
    '',
    '## Components',
    '',
    table,
    names.map((n) => {
      const m = meta('components', n);
      return row(m.title, m.description, docPath.component(n));
    }),
    '',
    '## Blocks',
    '',
    'Page sections built from the components. The block doc lists which components to install first.',
    '',
    table,
    blocks.map((n) => {
      const m = meta('blocks', n);
      return row(m.title, m.description, docPath.block(n));
    }),
    '',
    '## Maintainers',
    '',
    `Generated from \`packages/ui/src\`, \`prompts/\` and \`apps/docs/examples/\` by \`npm run gen:ai\`; CI fails when \`ai/\` is out of date. Repo and branch for the URLs: \`${GH_REPO}\` / \`${GH_BRANCH}\` (constants in \`scripts/lib/ai-docs.mjs\`).`,
  );
}

/* ---------------------------------------------------------------------------
   Write */

function write(path, text) {
  const abs = join(repoRoot, path);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, `${text.trimEnd()}\n`);
}

const blockDir = join(repoRoot, 'apps', 'docs', 'examples', 'blocks');
const blocks = existsSync(blockDir)
  ? readdirSync(blockDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
  : [];

rmSync(OUT, { recursive: true, force: true });
write(docPath.setup, setupDoc());
for (const n of names) write(docPath.component(n), componentDoc(n));
for (const n of blocks) write(docPath.block(n), blockDoc(n));
write(docPath.readme, readme(blocks));

console.log(`gen-ai-docs: ${names.length} components, ${blocks.length} blocks → ai/  [${GH_REPO}@${GH_BRANCH}]`);
for (const w of [...new Set(warnings)].sort()) console.log(`gen-ai-docs: warning: ${w}`);
